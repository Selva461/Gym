package dev.avles.gym.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * Palette notes.
 *
 * This app is opened at 8:50 PM in a gym and again at 10 PM before bed. It never
 * meets daylight, so there is no light scheme — a dark-only app that is honestly
 * dark beats one that flickers white on launch.
 *
 * The base is blue-black rather than a tinted grey: at night a slight indigo cast
 * reads as evening instead of as a switched-off screen. Two accents carry meaning
 * rather than decoration — brass is always training, sage is always food. When a
 * number is brass you know without reading the label which half of the app you're in.
 */
val Ink = Color(0xFF12141C)
val Slate = Color(0xFF1B1F2B)
val Raised = Color(0xFF232837)
val Line = Color(0xFF2A3040)
val Bone = Color(0xFFE8E6E1)
val Mute = Color(0xFF8A91A3)
val Faint = Color(0xFF5A6175)

val Brass = Color(0xFFF2A93B)
val Sage = Color(0xFF6FBF8B)
val Coral = Color(0xFFE05C5C)
